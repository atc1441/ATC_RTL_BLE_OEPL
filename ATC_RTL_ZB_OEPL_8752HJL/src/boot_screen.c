#define EPD_WIDTH 480
#define EPD_HEIGHT 224
#define BYTES_PER_ROW 120
#define MAX_CHARS 60
#define CHAR_H 24
#define V_WIDTH 480
#define V_HEIGHT 224
#define P_WIDTH 224
#define P_HEIGHT 480

static bool is_pixel_black(int vx, int vy, const char *const *lines, int n_lines, int ly_start)
{
    int rel_vy = vy - ly_start;
    if (rel_vy < 0)
        return false;

    int line = rel_vy / CHAR_H;
    int fr = (rel_vy % CHAR_H) / 2;
    if (line >= 0 && line < n_lines && fr < 8)
    {
        int char_idx = vx / 8;
        int font_bit = (vx % 8);
        if (char_idx >= 0 && char_idx < (int)strlen(lines[line]))
        {
            uint8_t c = (uint8_t)lines[line][char_idx];
            if (c >= 0x20 && c <= 0x7E)
            {
                return (font8[c - 0x20][fr] & (1 << font_bit)) != 0;
            }
        }
    }
    return false;
}

static void render_lines_rotated(const char *const *lines, int n_lines)
{
    const int ly_start = (V_HEIGHT - n_lines * CHAR_H) / 2;

    epd_cmd(0x10);

    for (int yp = 0; yp < P_HEIGHT; yp++)
    {
        for (int xp_byte = 0; xp_byte < 56; xp_byte++)
        {
            uint8_t out_byte = 0;

            for (int p = 0; p < 4; p++)
            {
                int xp = xp_byte * 4 + p;
                int vx = yp;

                int vy = (V_HEIGHT - 1) - xp;

                out_byte <<= 2;
                if (is_pixel_black(vx, vy, lines, n_lines, ly_start))
                {
                    out_byte |= 0x00;
                }
                else
                {
                    out_byte |= 0x01;
                }
            }
            epd_data(out_byte);
        }
    }
}

void boot_screen_show_error(const char *const *lines, uint8_t n_lines)
{
    epd_board_init();
    epd_init();
    render_lines_rotated(lines, (int)n_lines);

    printf("EPD_ERR refresh triggered\n");
    epd_cmd(0x04);
    epd_wait_busy();
    epd_write(0x12, 1, 0x00);
    epd_wait_busy_sleep();
    epd_sleep();
    printf("Refresh finished.\n");
}

void status_screen_show(const uint8_t *mac8, uint16_t battery_mv,
                        uint8_t channel, const char *status)
{
    char ln[8][80];

    snprintf(ln[0], sizeof(ln[0]), " OpenEPaperLink  RTL8752HJL");
    snprintf(ln[1], sizeof(ln[1]), " MAC: %02X:%02X:%02X:%02X:%02X:%02X:%02X:%02X", mac8[7], mac8[6], mac8[5], mac8[4], mac8[3], mac8[2], mac8[1], mac8[0]);
    if (!channel)
        snprintf(ln[2], sizeof(ln[2]), " BAT: %u mV    CH: scanning", battery_mv);
    else
        snprintf(ln[2], sizeof(ln[2]), " BAT: %u mV    CH: %u", battery_mv, channel);
    snprintf(ln[3], sizeof(ln[3]), " AP:  %02X:%02X:%02X:%02X:%02X:%02X:%02X:%02X", APmac[7], APmac[6], APmac[5], APmac[4], APmac[3], APmac[2], APmac[1], APmac[0]);
    snprintf(ln[4], sizeof(ln[4]), " RSSI: %d dBm", (int)mLastRSSI);
    snprintf(ln[5], sizeof(ln[5]), " FW: v%04X", (unsigned)FIRMWARE_VERSION);
    snprintf(ln[6], sizeof(ln[6]), " ATC1441 Compiled on: " __DATE__ " " __TIME__);
    snprintf(ln[7], sizeof(ln[7]), " >> %s", status ? status : "");

    const char *ptrs[8] = {ln[0], ln[1], ln[2], ln[3], ln[4], ln[5], ln[6], ln[7]};

    epd_board_init();
    epd_init();
    render_lines_rotated(ptrs, 8);

    printf("STATUS: %s  ch=%u  bat=%u mV\n", status, channel, battery_mv);
    epd_cmd(0x04);
    epd_wait_busy();
#if DO_EPD_REFRESH
    epd_write(0x12, 1, 0x00);
#endif
    epd_wait_busy();
    epd_sleep();
    printf("Refresh finished.\n");
}