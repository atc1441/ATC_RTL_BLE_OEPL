/* The normal OEPL/HA image path is now aligned with the physical 9.7" tag.
 * The boot screen, however, has to be rotated by 180 degrees to match that
 * physical orientation.
 *
 * The controller itself already reverses the BYTE order of a streamed row
 * (X-decrement addressing). For a full 180-degree boot-screen rotation we:
 *   1. render source rows from bottom to top (Y flip), and
 *   2. reverse the BITS in each byte before streaming.
 *
 * The controller's byte-order reversal + our bit reversal together produce
 * the required full horizontal pixel reversal. */
static inline uint8_t bit_rev8(uint8_t b)
{
    b = (uint8_t)((b >> 4) | (b << 4));
    b = (uint8_t)(((b & 0xCCu) >> 2) | ((b & 0x33u) << 2));
    b = (uint8_t)(((b & 0xAAu) >> 1) | ((b & 0x55u) << 1));
    return b;
}

/* Return the EPD byte for character c at font row fr (0-7).
 * BW RAM is active-low in this driver, hence the inversion. */
static inline uint8_t char_byte(char c, int fr)
{
    if (fr < 0 || fr > 7 || c < 0x20 || c > 0x7E)
        return 0xFF;
    return (uint8_t)~font8[(uint8_t)c - 0x20][fr];
}

/* ---- Layout constants ---------------------------------------------------- */
#define ROW_BYTES   EPD_ROW_BYTES /* 120 bytes = 960 pixels */
#define CHAR_H      20    /* text row height: 8-pt font × 2× (16 px) + 4 px gap */
#define EPH         EPD_HEIGHT

/* ---- Shared rendering helper --------------------------------------------- */

/* Write all BW + Red RAM for `n_lines` strings, centred vertically.
 * EPD must be initialised before calling this. Does NOT trigger refresh. */
static void render_lines(const char * const *lines, int n_lines)
{
    const int y_start = (EPH - n_lines * CHAR_H) / 2;
    uint8_t row[ROW_BYTES];

    epd_begin_bw();
    for (int out_y = 0; out_y < EPH; out_y++) {
        /* 180-degree rotation: take the logical source row from bottom to top. */
        int y = (EPH - 1) - out_y;
        int text_y = y - y_start;
        int line   = text_y / CHAR_H;
        int fr     = (text_y % CHAR_H) / 2;

        row[ROW_BYTES - 1] = 0xFF;
        for (int c = 0; c < ROW_BYTES - 1; c++) {
            uint8_t b = 0xFF;
            if (text_y >= 0 && line >= 0 && line < n_lines) {
                int len = (int)strlen(lines[line]);
                if (c < len)
                    b = char_byte(lines[line][c], fr);
            }
            row[c] = b;
        }

        /* The controller reverses byte positions itself. Reversing the bits
         * in each source byte completes the horizontal half of the 180°
         * rotation without touching the working OEPL/HA drawing path. */
        for (uint32_t i = 0; i < ROW_BYTES; i++)
            row[i] = bit_rev8(row[i]);

        epd_stream_data(row, ROW_BYTES);
    }

    /* Red RAM: no colour. */
    epd_begin_red();
    epd_stream_const(0x00, EPD_BUF_SIZE);
}

/* ---- Public API ---------------------------------------------------------- */

void boot_screen_draw(const uint8_t *ble_addr_6, uint16_t battery_mv)
{
    char ln[6][80];
    snprintf(ln[0], sizeof(ln[0]), " OpenEpaperLink RTL8762ESL");
    snprintf(ln[1], sizeof(ln[1]), " BLE Name: RTL_%02X%02X%02X",
             ble_addr_6[2], ble_addr_6[1], ble_addr_6[0]);
    snprintf(ln[2], sizeof(ln[2]), " MAC: %02X:%02X:%02X:%02X:%02X:%02X",
             ble_addr_6[5], ble_addr_6[4], ble_addr_6[3],
             ble_addr_6[2], ble_addr_6[1], ble_addr_6[0]);
    snprintf(ln[3], sizeof(ln[3]), " BAT: %u mV", battery_mv);
    snprintf(ln[4], sizeof(ln[4]), " FW:  v%04X", (unsigned)FIRMWARE_VERSION);
    snprintf(ln[5], sizeof(ln[5]), " ATC1441 Compiled on: " __DATE__ " " __TIME__);

    const char *ptrs[6] = { ln[0], ln[1], ln[2], ln[3], ln[4], ln[5] };

    epd_board_init();
    epd_init();
    render_lines(ptrs, 6);

    /* The DLPS refresh guard blocks DLPS for the complete physical refresh.
     * Give the 60 s AON watchdog a fresh full timeout window first. */
    AON_WDG_Restart();
    g_epd_refreshing = true;
    epd_refresh();
    printf("BOOT refresh triggered\n");
}

void boot_screen_show_error(const char * const *lines, uint8_t n_lines)
{
    epd_board_init();
    epd_init();
    render_lines(lines, (int)n_lines);

    /* Same rule for OTA/error screens: refresh may keep DLPS blocked ~24 s. */
    AON_WDG_Restart();
    g_epd_refreshing = true;
    epd_refresh();
    printf("EPD_ERR refresh triggered\n");
}
